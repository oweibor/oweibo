function buildBundleSignScript(): string {
  return `#!/usr/bin/env node
// scripts/sign-bundle.js — generated by oweibo module-export
// Computes HMAC-SHA256 signature over all artifact files for integrity verification.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SECRET = process.env.BUNDLE_SIGNING_SECRET;
if (!SECRET) { console.error('[sign-bundle] BUNDLE_SIGNING_SECRET env var required'); process.exit(1); }

const DIST_DIR = process.argv[2] ?? path.join(__dirname, '..', 'dist');
if (!fs.existsSync(DIST_DIR)) { console.error(\`[sign-bundle] Directory not found: \${DIST_DIR}\`); process.exit(1); }

function collectFiles(dir, base = dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const result = [];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...collectFiles(full, base));
    else result.push(path.relative(base, full).replace(/\\\\/g, '/'));
  }
  return result;
}

const files = collectFiles(DIST_DIR);
const hmac = crypto.createHmac('sha256', SECRET);
for (const f of files) {
  const content = fs.readFileSync(path.join(DIST_DIR, f));
  hmac.update(\`\${f}:\`);
  hmac.update(content);
}
const signature = hmac.digest('hex');
const manifest = { version: '1', algorithm: 'hmac-sha256', files, signature, signedAt: new Date().toISOString() };
const outPath = path.join(DIST_DIR, 'bundle.sig.json');
fs.writeFileSync(outPath, JSON.stringify(manifest, null, 2));
console.log(\`[sign-bundle] Signature: \${signature}\`);
console.log(\`[sign-bundle] Manifest written to \${outPath}\`);
`;
}

function buildVerifyScript(): string {
  return `#!/usr/bin/env node
// scripts/verify-bundle.js — generated by oweibo module-export
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const SECRET = process.env.BUNDLE_SIGNING_SECRET;
if (!SECRET) { console.error('[verify-bundle] BUNDLE_SIGNING_SECRET env var required'); process.exit(1); }

const SIG_FILE = process.argv[2] ?? path.join(__dirname, '..', 'dist', 'bundle.sig.json');
if (!fs.existsSync(SIG_FILE)) { console.error(\`[verify-bundle] Signature file not found: \${SIG_FILE}\`); process.exit(1); }

const manifest = JSON.parse(fs.readFileSync(SIG_FILE, 'utf-8'));
const distDir = path.dirname(SIG_FILE);
const hmac = crypto.createHmac('sha256', SECRET);
for (const f of manifest.files) {
  const filePath = path.join(distDir, f);
  if (!fs.existsSync(filePath)) { console.error(\`[verify-bundle] Missing file: \${f}\`); process.exit(2); }
  const content = fs.readFileSync(filePath);
  hmac.update(\`\${f}:\`);
  hmac.update(content);
}
const computed = hmac.digest('hex');
if (computed !== manifest.signature) {
  console.error(\`[verify-bundle] SIGNATURE MISMATCH\`);
  console.error(\`  expected: \${manifest.signature}\`);
  console.error(\`  computed: \${computed}\`);
  process.exit(3);
}
console.log('[verify-bundle] Bundle signature VALID');
`;
}

