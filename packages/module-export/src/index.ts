export class ExportGenerator implements IModuleGenerator {
  readonly manifest: IModuleManifest = MANIFEST;

  async generate(reader: IBlueprintReader, api: IGeneratorAPI): Promise<ArtifactBundle> {
    const input = reader.getScaffoldInput();
    const appName = input.appName;
    const registry = ((input as unknown as Record<string, unknown>)['containerRegistry'] as string | undefined) ?? 'ghcr.io/oweibo';
    const database = input.database ?? 'postgresql';
    const files: ArtifactFile[] = [];

    const fileMap: Record<string, string> = {
      'docker/manifest.json':                            buildDockerManifest(appName, registry),
      '.dockerignore':                                   buildDockerignore(),
      'scripts/dump.sh':                                 buildSqlDumpScript(database),
      'scripts/sign-bundle.js':                          buildBundleSignScript(),
      'scripts/verify-bundle.js':                        buildVerifyScript(),
      'helm/Chart.yaml':                                 buildHelmChart(appName),
      'helm/values.yaml':                                buildHelmValues(appName, registry),
      'helm/templates/deployment.yaml':                  buildHelmTemplateDeployment(appName),
      'k8s/overlays/production/kustomization.yaml':      buildK8sProductionOverlay(appName, registry),
      '.github/workflows/release.yml':                   buildGithubActionsRelease(appName, registry),
    };

    for (const [path, content] of Object.entries(fileMap)) {
      await api.writeFile(path, content);
      files.push(file(path, content));
    }

    // Compute deterministic bundle signature over all file paths + checksums
    const sigPayload = files.map(f => `${f.path}:${f.checksum}`).join('\n');
    const signature = createHmac('sha256', 'oweibo-internal-signing-seed').update(sigPayload).digest('hex');

    const testContent = buildExportTest();
    await api.writeFile('src/__tests__/export.contract.test.ts', testContent);

    const k8sManifests = [file('k8s/overlays/production/kustomization.yaml', fileMap['k8s/overlays/production/kustomization.yaml']!)];

    return {
      files,
      testFiles: [file('src/__tests__/export.contract.test.ts', testContent)],
      dbMigrations: [],
      k8sManifests,
      docFiles: [],
      knowledgeArtifact: {
        moduleName: 'module-export',
        version: MANIFEST.version,
        generatedAt: new Date().toISOString(),
        domainDescription: `Export & packaging layer: Docker manifests, Helm charts, K8s overlays, SQL dump scripts, and HMAC-signed artifact bundles.`,
        entities: [],
        endpoints: [],
        emittedEvents: [],
        consumedEvents: [],
        invariants: [
          { description: 'All artifact bundles must carry an HMAC-SHA256 signature', source: 'annotation', filePath: 'scripts/sign-bundle.js' },
          { description: 'Production K8s overlay must set replica count >= 2', source: 'annotation', filePath: 'k8s/overlays/production/kustomization.yaml' },
        ],
        extensionPoints: [
          { hookName: 'addHelmTemplate', filePath: 'helm/templates/', description: 'Add Helm template files for additional K8s resources' },
          { hookName: 'extendDockerfile', filePath: 'Dockerfile', description: 'Extend the generated Dockerfile with custom build steps' },
        ],
        userFlows: [
          { name: 'Release pipeline', actor: 'CI/CD', steps: ['git tag v1.0.0', 'push triggers release.yml', 'Docker image built & pushed', 'bundle signed'], outcome: 'Signed container image published to registry' },
          { name: 'Verify bundle integrity', actor: 'DevOps', steps: ['run scripts/verify-bundle.js'], outcome: 'Bundle signature validated' },
        ],
        glossary: [
          { term: 'Bundle signature', definition: 'HMAC-SHA256 digest over all artifact paths and their checksums, proving integrity' },
          { term: 'Helm chart', definition: 'Kubernetes package manager chart for deploying the application' },
        ],
        exampleUsages: [],
      },
      signature,
    };
  }

  validate(bundle: ArtifactBundle): ValidationResult {
    const errors: Array<{ code: string; message: string }> = [];
    if (bundle.files.length === 0) errors.push({ code: 'EMPTY_BUNDLE', message: 'Export module produced no files' });
    if (!bundle.files.find(f => f.path.includes('helm'))) errors.push({ code: 'MISSING_HELM', message: 'Helm chart is required for production export' });
    if (!bundle.files.find(f => f.path.includes('sign-bundle'))) errors.push({ code: 'MISSING_SIGN_SCRIPT', message: 'Bundle signing script is required' });
    if (bundle.testFiles.length === 0) errors.push({ code: 'MISSING_TESTS', message: 'Contract test required' });
    if (!bundle.signature) errors.push({ code: 'MISSING_SIGNATURE', message: 'Bundle must carry an HMAC signature' });
    return { valid: errors.length === 0, errors, warnings: [] };
  }
}

export default ExportGenerator;
