function buildScaffoldingTest(input: ScaffoldInput): string {
  return `// module-scaffolding.contract.test.ts
// Contract test: verifies scaffold output meets IModuleGenerator contract.
import { ScaffoldingGenerator } from '../index';
import type { IBlueprintReader, IGeneratorAPI, ArtifactBundle } from '@oweibo/core-contracts';

const mockInput = {
  appName: '${input.appName}',
  stack: '${input.stack}' as const,
  database: '${input.database}' as const,
  features: [],
  tenantId: 'test-tenant',
  hardwareProfile: 'core_i5' as const,
};

const mockReader: IBlueprintReader = {
  getScaffoldInput: () => mockInput,
  readFile: async () => null,
  listFiles: async () => [],
};

const files = new Map<string, string>();
const mockApi: IGeneratorAPI = {
  writeFile: async (path, content) => { files.set(path, content); },
  appendFile: async (path, content) => { files.set(path, (files.get(path) ?? '') + content); },
  deleteFile: async (path) => { files.delete(path); },
  runShellCommand: async () => ({ stdout: '', stderr: '', exitCode: 0 }),
  getArchitectOutput: () => undefined,
  getExecutorOutput: () => undefined,
};

describe('ScaffoldingGenerator', () => {
  let bundle: ArtifactBundle;

  beforeAll(async () => {
    const gen = new ScaffoldingGenerator();
    bundle = await gen.generate(mockReader, mockApi);
  });

  it('produces non-empty files array', () => {
    expect(bundle.files.length).toBeGreaterThan(0);
  });

  it('includes package.json', () => {
    const pkg = bundle.files.find(f => f.path === 'package.json');
    expect(pkg).toBeDefined();
    expect(JSON.parse(pkg!.content)).toHaveProperty('scripts.test');
  });

  it('includes tsconfig.json', () => {
    expect(bundle.files.find(f => f.path === 'tsconfig.json')).toBeDefined();
  });

  it('includes a health endpoint', () => {
    expect(bundle.files.find(f => f.path.includes('health'))).toBeDefined();
  });

  it('passes validation', () => {
    const gen = new ScaffoldingGenerator();
    const result = gen.validate(bundle);
    expect(result.valid).toBe(true);
    expect(result.errors).toHaveLength(0);
  });
});
`;
}

// ─── Generator class ─────────────────────────────────────────────────────────

export class ScaffoldingGenerator implements IModuleGenerator {
  readonly manifest: IModuleManifest = MANIFEST;

  async generate(reader: IBlueprintReader, api: IGeneratorAPI): Promise<ArtifactBundle> {
    const input = reader.getScaffoldInput();
    const files: ArtifactFile[] = [];

    const fileMap: Record<string, string> = {
      'package.json':             buildPackageJson(input),
      'tsconfig.json':            buildTsConfig(input),
      'Dockerfile':               buildDockerfile(input),
      '.gitignore':               buildGitIgnore(),
      '.eslintrc.json':           buildEslintConfig(),
      'src/routes/health.ts':     buildHealthEndpoint(input),
      '.env.example':             `NODE_ENV=development\nPORT=3000\nDATABASE_URL=\nREDIS_URL=\n`,
      'README.md':                `# ${input.appName}\n\nGenerated by oweibo.\n\n## Quick Start\n\n\`\`\`bash\nnpm install\nnpm run dev\n\`\`\`\n`,
    };

    for (const [path, content] of Object.entries(fileMap)) {
      await api.writeFile(path, content);
      files.push(file(path, content));
    }

    const testContent = buildScaffoldingTest(input);
    await api.writeFile('src/__tests__/scaffolding.contract.test.ts', testContent);
    const testFile = file('src/__tests__/scaffolding.contract.test.ts', testContent);

    return {
      files,
      testFiles: [testFile],
      dbMigrations: [],
      k8sManifests: [],
      docFiles: [],
      knowledgeArtifact: {
        moduleName: 'module-scaffolding',
        version: MANIFEST.version,
        generatedAt: new Date().toISOString(),
        domainDescription: 'Base project scaffold providing directory structure, tooling config, and health endpoints.',
        entities: [],
        endpoints: [{ method: 'GET', path: '/health', filePath: 'src/routes/health.ts', description: 'Health check endpoint' }],
        emittedEvents: [],
        consumedEvents: [],
        invariants: [{ description: '/health must return 200 with status:ok', source: 'annotation', filePath: 'src/routes/health.ts' }],
        extensionPoints: [],
        userFlows: [{ name: 'Check service health', actor: 'DevOps', steps: ['GET /health'], outcome: 'Service status confirmed as ok' }],
        glossary: [{ term: 'Scaffold', definition: 'The base project structure that all other modules build upon' }],
        exampleUsages: [],
      },
      signature: '',
    };
  }

  validate(bundle: ArtifactBundle): ValidationResult {
    const errors: Array<{ code: string; message: string; filePath?: string }> = [];

    if (bundle.files.length === 0) {
      errors.push({ code: 'EMPTY_BUNDLE', message: 'Scaffold produced no files' });
    }
    if (!bundle.files.find(f => f.path === 'package.json')) {
      errors.push({ code: 'MISSING_PACKAGE_JSON', message: 'package.json is required' });
    }
    if (!bundle.files.find(f => f.path === 'tsconfig.json')) {
      errors.push({ code: 'MISSING_TSCONFIG', message: 'tsconfig.json is required' });
    }
    if (!bundle.files.find(f => f.path.includes('health'))) {
      errors.push({ code: 'MISSING_HEALTH_ENDPOINT', message: 'A /health endpoint file is required (SmokeTestStage gate)' });
    }
    if (bundle.testFiles.length === 0) {
      errors.push({ code: 'MISSING_TESTS', message: 'At least one test file is required (TDD gate)' });
    }

    return { valid: errors.length === 0, errors, warnings: [] };
  }
}

export default ScaffoldingGenerator;
