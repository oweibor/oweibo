/**
 * @oweibo/module-scaffolding
 *
 * Generates the base project scaffold: directory structure, package.json,
 * tsconfig, ESLint config, Prettier, .gitignore, Docker files, and CI configs.
 * Always the first module to run — all other modules build on top of its output.
 *
 * Implements IModuleGenerator (core-contracts only — no core-engine imports).
 */
import type {
  IModuleGenerator,
  IModuleManifest,
  IBlueprintReader,
  IGeneratorAPI,
  ArtifactBundle,
  ArtifactFile,
  ValidationResult,
  ScaffoldInput,
} from '@oweibo/core-contracts';
import { createHash } from 'crypto';

function checksum(content: string): string {
  return createHash('sha256').update(content, 'utf-8').digest('hex');
}

function file(path: string, content: string): ArtifactFile {
  return { path, content, encoding: 'utf-8', checksum: checksum(content) };
}

// ─── Manifest ────────────────────────────────────────────────────────────────

const MANIFEST: IModuleManifest = {
  name: 'module-scaffolding',
  version: '0.1.0',
  coreContractsVersion: '>=0.1.0',
  emits: ['scaffolding:completed'],
  consumes: [],
  knowledgeArtifactPath: 'knowledge/module-scaffolding.json',
};

// ─── Template builders ───────────────────────────────────────────────────────

function buildPackageJson(input: ScaffoldInput): string {
  const stackDeps: Record<string, Record<string, string>> = {
    t3: {
      next: '^14.0.0', react: '^18.0.0', 'react-dom': '^18.0.0',
      '@trpc/server': '^11.0.0', '@trpc/client': '^11.0.0',
    },
    nextjs: { next: '^14.0.0', react: '^18.0.0', 'react-dom': '^18.0.0' },
    express: { express: '^4.18.0', cors: '^2.8.5', helmet: '^7.0.0' },
    mern: { express: '^4.18.0', mongoose: '^8.0.0', react: '^18.0.0' },
    laravel: {},
    django: {},
  };
  const deps = stackDeps[input.stack] ?? {};

  return JSON.stringify({
    name: input.appName.toLowerCase().replace(/\s+/g, '-'),
    version: '0.1.0',
    private: true,
    scripts: {
      dev: input.stack === 'nextjs' || input.stack === 't3' ? 'next dev' : 'ts-node-dev src/index.ts',
      build: input.stack === 'nextjs' || input.stack === 't3' ? 'next build' : 'tsc',
      start: input.stack === 'nextjs' || input.stack === 't3' ? 'next start' : 'node dist/index.js',
      test: 'jest --passWithNoTests',
      lint: 'eslint . --ext .ts,.tsx',
      typecheck: 'tsc --noEmit',
    },
    dependencies: {
      ...deps,
      zod: '^3.23.0',
    },
    devDependencies: {
      typescript: '^5.5.0',
      '@types/node': '^20.0.0',
      jest: '^29.0.0',
      'ts-jest': '^29.0.0',
      '@types/jest': '^29.0.0',
      eslint: '^8.0.0',
      '@typescript-eslint/eslint-plugin': '^7.0.0',
      '@typescript-eslint/parser': '^7.0.0',
      prettier: '^3.0.0',
      rimraf: '^5.0.0',
    },
  }, null, 2);
}

function buildTsConfig(input: ScaffoldInput): string {
  const isNext = input.stack === 'nextjs' || input.stack === 't3';
  return JSON.stringify({
    compilerOptions: {
      target: 'ES2022',
      lib: isNext ? ['dom', 'dom.iterable', 'esnext'] : ['ES2022'],
      module: isNext ? 'esnext' : 'Node16',
      moduleResolution: isNext ? 'bundler' : 'Node16',
      jsx: isNext ? 'preserve' : undefined,
      strict: true,
      noUncheckedIndexedAccess: true,
      exactOptionalPropertyTypes: true,
      outDir: './dist',
      rootDir: './src',
      declaration: true,
      declarationMap: true,
      sourceMap: true,
      skipLibCheck: true,
      forceConsistentCasingInFileNames: true,
    },
    include: ['src'],
    exclude: ['node_modules', 'dist'],
  }, null, 2);
}

function buildDockerfile(input: ScaffoldInput): string {
  return `# Generated by oweibo module-scaffolding
FROM node:20-alpine AS base
WORKDIR /app
COPY package*.json ./
RUN npm ci --only=production

FROM base AS builder
RUN npm ci
COPY . .
RUN npm run build

FROM base AS runner
COPY --from=builder /app/dist ./dist
EXPOSE 3000
ENV NODE_ENV=production
CMD ["node", "dist/index.js"]
`;
}

