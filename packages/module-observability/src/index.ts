function buildMetricsMiddleware(appName: string): string {
  return `// src/observability/metrics.ts — generated by oweibo module-observability
import { Registry, Counter, Histogram, Gauge, collectDefaultMetrics } from 'prom-client';
import type { Request, Response, NextFunction } from 'express';

export const register = new Registry();
register.setDefaultLabels({ app: '${appName.toLowerCase().replace(/\s+/g, '-')}' });
collectDefaultMetrics({ register });

export const httpRequestsTotal = new Counter({
  name: 'http_requests_total',
  help: 'Total number of HTTP requests',
  labelNames: ['method', 'route', 'status_code'] as const,
  registers: [register],
});

export const httpRequestDurationMs = new Histogram({
  name: 'http_request_duration_ms',
  help: 'HTTP request duration in milliseconds',
  labelNames: ['method', 'route', 'status_code'] as const,
  buckets: [5, 10, 25, 50, 100, 250, 500, 1000, 2500, 5000],
  registers: [register],
});

export const activeConnections = new Gauge({
  name: 'http_active_connections',
  help: 'Number of active HTTP connections',
  registers: [register],
});

export const taskQueueDepth = new Gauge({
  name: 'oweibo_task_queue_depth',
  help: 'Number of tasks currently queued for processing',
  labelNames: ['tenant_id'] as const,
  registers: [register],
});

export const llmCallsTotal = new Counter({
  name: 'oweibo_llm_calls_total',
  help: 'Total LLM API calls',
  labelNames: ['model', 'stage', 'status'] as const,
  registers: [register],
});

export const llmTokensUsed = new Counter({
  name: 'oweibo_llm_tokens_total',
  help: 'Total tokens consumed by LLM calls',
  labelNames: ['model', 'type'] as const,
  registers: [register],
});

/** Express middleware that records latency and status for every request. */
export function metricsMiddleware(req: Request, res: Response, next: NextFunction): void {
  const start = Date.now();
  activeConnections.inc();
  res.on('finish', () => {
    const duration = Date.now() - start;
    const route = (req.route?.path as string | undefined) ?? req.path;
    const labels = { method: req.method, route, status_code: String(res.statusCode) };
    httpRequestsTotal.inc(labels);
    httpRequestDurationMs.observe(labels, duration);
    activeConnections.dec();
  });
  next();
}

/** Route handler for GET /metrics — returns Prometheus text format. */
export async function metricsHandler(req: Request, res: Response): Promise<void> {
  try {
    res.set('Content-Type', register.contentType);
    res.end(await register.metrics());
  } catch (err) {
    res.status(500).end(String(err));
  }
}
`;
}

function buildLogger(appName: string): string {
  return `// src/observability/logger.ts — generated by oweibo module-observability
import { createLogger, format, transports } from 'winston';
import type { Logger } from 'winston';

const { combine, timestamp, json, errors, colorize, simple } = format;

const isDev = process.env.NODE_ENV === 'development';

export const logger: Logger = createLogger({
  level: process.env.LOG_LEVEL ?? (isDev ? 'debug' : 'info'),
  defaultMeta: { service: '${appName.toLowerCase().replace(/\s+/g, '-')}' },
  format: isDev
    ? combine(colorize(), timestamp(), simple())
    : combine(errors({ stack: true }), timestamp(), json()),
  transports: [
    new transports.Console(),
  ],
  exitOnError: false,
});

/** Child logger scoped to a specific module/context. */
export function childLogger(context: string): Logger {
  return logger.child({ context });
}

/** Log an error with structured metadata. */
export function logError(err: unknown, context?: Record<string, unknown>): void {
  if (err instanceof Error) {
    logger.error(err.message, { stack: err.stack, ...context });
  } else {
    logger.error(String(err), context);
  }
}

export default logger;
`;
}

