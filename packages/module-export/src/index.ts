function buildDockerManifest(appName: string, registry: string): string {
  const safeName = appName.toLowerCase().replace(/\s+/g, '-');
  return JSON.stringify({
    schemaVersion: 2,
    mediaType: 'application/vnd.docker.distribution.manifest.v2+json',
    config: {
      mediaType: 'application/vnd.docker.container.image.v1+json',
      size: 0,
      digest: `sha256:${'0'.repeat(64)}`,
    },
    layers: [],
    annotations: {
      'org.opencontainers.image.title': safeName,
      'org.opencontainers.image.version': '0.1.0',
      'org.opencontainers.image.source': `${registry}/${safeName}`,
      'org.opencontainers.image.created': new Date().toISOString(),
      'com.oweibo.generated': 'true',
    },
  }, null, 2);
}

