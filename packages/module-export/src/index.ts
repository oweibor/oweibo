function buildSqlDumpScript(database: string): string {
  if (database === 'sqlite') {
    return `#!/usr/bin/env bash
# dump.sh — SQLite export script generated by oweibo module-export
set -euo pipefail

DB_FILE="\${DB_FILE:-./prisma/dev.db}"
OUTPUT_DIR="\${OUTPUT_DIR:-./exports}"
TIMESTAMP=\$(date +%Y%m%d_%H%M%S)
OUTPUT_FILE="\${OUTPUT_DIR}/dump_\${TIMESTAMP}.sql"

mkdir -p "\${OUTPUT_DIR}"
sqlite3 "\${DB_FILE}" .dump > "\${OUTPUT_FILE}"
echo "[export] SQLite dump written to \${OUTPUT_FILE}"
`;
  }
  return `#!/usr/bin/env bash
# dump.sh — PostgreSQL export script generated by oweibo module-export
set -euo pipefail

DATABASE_URL="\${DATABASE_URL:?DATABASE_URL is required}"
OUTPUT_DIR="\${OUTPUT_DIR:-./exports}"
TIMESTAMP=\$(date +%Y%m%d_%H%M%S)
OUTPUT_FILE="\${OUTPUT_DIR}/dump_\${TIMESTAMP}.sql"

mkdir -p "\${OUTPUT_DIR}"
pg_dump --no-owner --no-acl "\${DATABASE_URL}" > "\${OUTPUT_FILE}"
gzip "\${OUTPUT_FILE}"
echo "[export] Dump written to \${OUTPUT_FILE}.gz"
`;
}

