/**
 * @oweibo/module-export
 *
 * Generates the Export & Packaging layer: signed Docker image manifests,
 * SQL dump scripts, K8s production overlays, Helm chart skeletons, and
 * HMAC-SHA256 bundle signatures for artifact integrity verification.
 *
 * Implements IModuleGenerator (core-contracts only — no core-engine imports).
 */
import type {
  IModuleGenerator,
  IModuleManifest,
  IBlueprintReader,
  IGeneratorAPI,
  ArtifactBundle,
  ArtifactFile,
  ValidationResult,
} from '@oweibo/core-contracts';
import { createHash, createHmac } from 'crypto';

function checksum(c: string): string { return createHash('sha256').update(c, 'utf-8').digest('hex'); }
function file(path: string, content: string): ArtifactFile {
  return { path, content, encoding: 'utf-8', checksum: checksum(content) };
}

