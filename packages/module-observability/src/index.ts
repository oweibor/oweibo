export class ObservabilityGenerator implements IModuleGenerator {
  readonly manifest: IModuleManifest = MANIFEST;

  async generate(reader: IBlueprintReader, api: IGeneratorAPI): Promise<ArtifactBundle> {
    const input = reader.getScaffoldInput();
    const appName = input.appName;
    const files: ArtifactFile[] = [];

    const fileMap: Record<string, string> = {
      'src/observability/metrics.ts':   buildMetricsMiddleware(appName),
      'src/observability/logger.ts':    buildLogger(appName),
      'src/observability/tracing.ts':   buildOtelConfig(),
      'src/routes/metrics.ts':          buildHealthWithMetrics(),
      'grafana/dashboard.json':         buildGrafanaDashboard(appName),
      'prometheus.yml':                 buildPrometheusConfig(appName),
    };

    for (const [path, content] of Object.entries(fileMap)) {
      await api.writeFile(path, content);
      files.push(file(path, content));
    }

    const testContent = buildObservabilityTest();
    await api.writeFile('src/__tests__/observability.contract.test.ts', testContent);

    return {
      files,
      testFiles: [file('src/__tests__/observability.contract.test.ts', testContent)],
      dbMigrations: [],
      k8sManifests: [],
      docFiles: [],
      knowledgeArtifact: {
        moduleName: 'module-observability',
        version: MANIFEST.version,
        generatedAt: new Date().toISOString(),
        domainDescription: `Observability layer: Prometheus metrics exposition, Winston structured logging, Grafana dashboard, and OpenTelemetry trace export.`,
        entities: [],
        endpoints: [{ method: 'GET', path: '/metrics', filePath: 'src/routes/metrics.ts', description: 'Prometheus metrics endpoint' }],
        emittedEvents: [],
        consumedEvents: [],
        invariants: [
          { description: 'All HTTP requests must be instrumented via metricsMiddleware', source: 'annotation', filePath: 'src/observability/metrics.ts' },
          { description: '/metrics endpoint must be accessible for Prometheus scraping', source: 'annotation', filePath: 'src/routes/metrics.ts' },
        ],
        extensionPoints: [
          { hookName: 'addCustomMetric', filePath: 'src/observability/metrics.ts', description: 'Register additional prom-client metrics (Counter, Histogram, Gauge)' },
          { hookName: 'addOtelInstrumentation', filePath: 'src/observability/tracing.ts', description: 'Add OpenTelemetry auto-instrumentation libraries' },
        ],
        userFlows: [
          { name: 'Observe system health', actor: 'DevOps', steps: ['Prometheus scrapes /metrics every 15s', 'Grafana queries Prometheus', 'Dashboard shows request rate & latency'], outcome: 'Real-time system visibility' },
        ],
        glossary: [
          { term: 'prom-client', definition: 'Node.js Prometheus client library for metrics exposition' },
          { term: 'OTLP', definition: 'OpenTelemetry Protocol — standard format for trace/metric/log export' },
        ],
        exampleUsages: [],
      },
      signature: '',
    };
  }

  validate(bundle: ArtifactBundle): ValidationResult {
    const errors: Array<{ code: string; message: string }> = [];
    if (bundle.files.length === 0) errors.push({ code: 'EMPTY_BUNDLE', message: 'Observability module produced no files' });
    if (!bundle.files.find(f => f.path.includes('metrics.ts'))) errors.push({ code: 'MISSING_METRICS', message: 'Prometheus metrics module required' });
    if (!bundle.files.find(f => f.path.includes('logger.ts'))) errors.push({ code: 'MISSING_LOGGER', message: 'Logger module required' });
    if (!bundle.files.find(f => f.path.includes('dashboard.json'))) errors.push({ code: 'MISSING_DASHBOARD', message: 'Grafana dashboard JSON required' });
    if (bundle.testFiles.length === 0) errors.push({ code: 'MISSING_TESTS', message: 'Contract test required' });
    return { valid: errors.length === 0, errors, warnings: [] };
  }
}

export default ObservabilityGenerator;
